#!/usr/bin/env bash
# Tests for bin/sync-opencode-commands.sh — the skill -> opencode slash-command
# generator (me2resh/apexyard#2064).
#
# Hermetic: every case builds its own fixture fork under a temp dir, so the
# checked-in .claude/skills tree and any real .opencode/commands output are
# never touched.

set -u

# Isolate from live Claude Code session pin/cache (me2resh/apexyard#1549).
# shellcheck disable=SC1091
. "$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)/_test-session-isolation.sh"

ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
SCRIPT="$ROOT/bin/sync-opencode-commands.sh"

red()   { printf '\033[31m%s\033[0m\n' "$*"; }
green() { printf '\033[32m%s\033[0m\n' "$*"; }

PASS=0
FAIL=0
FAILED=""

mark_pass() { green "  ok   $1"; PASS=$((PASS + 1)); }
mark_fail() {
  red "  FAIL $1: $2" >&2
  FAIL=$((FAIL + 1))
  FAILED="$FAILED $1"
}

assert_eq() {
  [ "$2" = "$3" ] && mark_pass "$1" || mark_fail "$1" "expected [$3] got [$2]"
}

assert_file() {
  [ -f "$2" ] && mark_pass "$1" || mark_fail "$1" "missing $2"
}

assert_no_file() {
  [ -f "$2" ] && mark_fail "$1" "unexpected $2" || mark_pass "$1"
}

assert_contains() {
  grep -qF "$2" "$3" 2>/dev/null && mark_pass "$1" || mark_fail "$1" "missing [$2] in $3"
}

assert_not_contains() {
  grep -qF "$2" "$3" 2>/dev/null && mark_fail "$1" "unexpected [$2] in $3" || mark_pass "$1"
}

# Frontmatter-only assertions: the hint must ride in the metadata block, not in
# the body, because opencode expands $ / @ / ! in the body as template syntax.
frontmatter_of() {
  awk 'NR == 1 && $0 == "---" { inside = 1; next } inside && $0 == "---" { exit } inside' "$1"
}

assert_frontmatter_contains() {
  case "$(frontmatter_of "$3")" in
    *"$2"*) mark_pass "$1" ;;
    *) mark_fail "$1" "frontmatter lacks [$2] in $3" ;;
  esac
}

unset CLAUDE_CODE_SESSION_ID
TMPBASE=$(mktemp -d "${TMPDIR:-/tmp}/sync-opencode-commands-test.XXXXXX") || exit 1
trap 'rm -rf "$TMPBASE"' EXIT

# Fixture fork: three usable skills, one dir without SKILL.md, one _lib helper
# file at the skills root, and one skill whose description carries the quoting
# hazards a real SKILL.md has (double quotes, backticks, colon, em dash).
make_fork() {
  local root="$1"
  mkdir -p "$root/.claude/skills/status" \
           "$root/.claude/skills/agdr" \
           "$root/.claude/skills/quote-hazards" \
           "$root/.claude/skills/no-skill-md"
  printf -- '---\nname: status\ndescription: Project snapshot — git state, open PRs.\nallowed-tools: Bash\n---\n\n# Status\n' \
    > "$root/.claude/skills/status/SKILL.md"
  printf -- '---\nname: agdr\ndescription: Browse AgDRs. Recalls "have we decided this before?".\nargument-hint: "[show <id>]"\n---\n\n# AgDR\n' \
    > "$root/.claude/skills/agdr/SKILL.md"
  printf -- '---\ndescription: "Quoted: description with `backticks` and a colon."\n---\n\n# Hazards\n' \
    > "$root/.claude/skills/quote-hazards/SKILL.md"
  printf 'not a skill\n' > "$root/.claude/skills/_lib-helper.sh"
  printf 'placeholder\n' > "$root/.claude/skills/no-skill-md/README.md"
}

FORK="$TMPBASE/fork"
make_fork "$FORK"
OUT="$FORK/.opencode/commands"

echo "generate"
bash "$SCRIPT" --root "$FORK" > "$TMPBASE/run1.log" 2>&1
assert_eq "exit 0 on first run" "$?" "0"
assert_file "status wrapper written" "$OUT/status.md"
assert_file "agdr wrapper written" "$OUT/agdr.md"
assert_file "quote-hazard wrapper written" "$OUT/quote-hazards.md"
assert_no_file "_lib helper is not a skill" "$OUT/_lib-helper.md"
assert_no_file "dir without SKILL.md is skipped" "$OUT/no-skill-md.md"
assert_eq "three wrappers, nothing else" "$(ls "$OUT" | wc -l | tr -d ' ')" "3"
assert_contains "description carried over" "Project snapshot — git state, open PRs." "$OUT/status.md"
assert_contains "quoted description unwrapped" "Quoted: description with" "$OUT/quote-hazards.md"
assert_frontmatter_contains "argument-hint folded into the frontmatter description" "Usage: [show <id>]" "$OUT/agdr.md"
assert_frontmatter_contains "argument-hint keeps the skill description" "Browse AgDRs" "$OUT/agdr.md"
assert_not_contains "argument-hint is not repeated in the body" "Usage for this command" "$OUT/agdr.md"
assert_contains "body loads the skill by exact id" 'Load the apexyard skill `status`' "$OUT/status.md"
assert_contains "body forwards arguments" '$ARGUMENTS' "$OUT/status.md"
assert_contains "generator marker present" "generated by bin/sync-opencode-commands.sh" "$OUT/status.md"

echo "idempotence"
bash "$SCRIPT" --root "$FORK" > "$TMPBASE/run2.log" 2>&1
assert_eq "exit 0 on second run" "$?" "0"
grep -q '0 written, 3 unchanged' "$TMPBASE/run2.log" \
  && mark_pass "second run rewrites nothing" \
  || mark_fail "second run rewrites nothing" "$(cat "$TMPBASE/run2.log")"

echo "--check"
bash "$SCRIPT" --root "$FORK" --check > "$TMPBASE/check1.log" 2>&1
assert_eq "clean --check exits 0" "$?" "0"

printf '\n<!-- hand edit -->\n' >> "$OUT/status.md"
bash "$SCRIPT" --root "$FORK" --check > "$TMPBASE/check2.log" 2>&1
assert_eq "drifted --check exits 1" "$?" "1"
assert_contains "drift names the file" "$OUT/status.md" "$TMPBASE/check2.log"
assert_contains "drifted file is left as-is by --check" "<!-- hand edit -->" "$OUT/status.md"

bash "$SCRIPT" --root "$FORK" > /dev/null 2>&1
assert_not_contains "regeneration reverts the drift" "<!-- hand edit -->" "$OUT/status.md"

echo "pruning"
cp "$OUT/status.md" "$OUT/gone-skill.md"
bash "$SCRIPT" --root "$FORK" --check > "$TMPBASE/check3.log" 2>&1
assert_eq "stale generated wrapper is drift" "$?" "1"
assert_file "stale wrapper survives --check" "$OUT/gone-skill.md"
bash "$SCRIPT" --root "$FORK" > "$TMPBASE/run3.log" 2>&1
assert_no_file "stale generated wrapper pruned" "$OUT/gone-skill.md"

printf 'Review $ARGUMENTS.\n' > "$OUT/handwritten.md"
bash "$SCRIPT" --root "$FORK" > /dev/null 2>&1
assert_file "hand-written wrapper is never pruned" "$OUT/handwritten.md"
rm -f "$OUT/handwritten.md"

echo "name conflicts"
# A hand-written file with a skill's name is the dangerous case: the directory
# is gitignored, so an overwrite is unrecoverable. It must be left alone in both
# modes, and --check must report a conflict rather than drift.
FORK2="$TMPBASE/fork-conflict"
mkdir -p "$FORK2/.claude/skills/status" "$FORK2/.opencode/commands"
printf -- '---\nname: status\ndescription: Project snapshot.\n---\n\n# Status\n' \
  > "$FORK2/.claude/skills/status/SKILL.md"
printf '# my own status command\n' > "$FORK2/.opencode/commands/status.md"
bash "$SCRIPT" --root "$FORK2" > "$TMPBASE/conflict1.log" 2>&1
assert_eq "hand-written conflict still exits 0" "$?" "0"
assert_contains "hand-written file is not overwritten" "my own status command" "$FORK2/.opencode/commands/status.md"
assert_contains "the conflict is named on stderr" "status.md" "$TMPBASE/conflict1.log"
bash "$SCRIPT" --root "$FORK2" --check > "$TMPBASE/conflict2.log" 2>&1
assert_eq "--check reports a conflict as no drift" "$?" "0"
assert_contains "--check names the conflict" "name conflict" "$TMPBASE/conflict2.log"

# A stale generated wrapper plus a name conflict must both be reported in one
# run, not only after the first is fixed. Copied from the first fixture so the
# file carries a real generator marker.
cp "$OUT/status.md" "$FORK2/.opencode/commands/gone.md"
bash "$SCRIPT" --root "$FORK2" --check > "$TMPBASE/conflict3.log" 2>&1
assert_eq "--check with drift and a conflict exits 1" "$?" "1"
assert_contains "--check still names the conflict alongside drift" "name conflict" "$TMPBASE/conflict3.log"
assert_contains "--check names the drifted file" "gone.md" "$TMPBASE/conflict3.log"

# A directory at the target path is not a regular file. `cp` would write the
# rendered wrapper inside it as `.../<id>.md/rendered`, so every run would write
# and --check would report drift forever. Report a conflict instead.
FORK6="$TMPBASE/fork-dir-target"
mkdir -p "$FORK6/.claude/skills/status" "$FORK6/.opencode/commands/status.md"
printf -- '---\nname: status\ndescription: Project snapshot.\n---\n\n# Status\n' \
  > "$FORK6/.claude/skills/status/SKILL.md"
bash "$SCRIPT" --root "$FORK6" > "$TMPBASE/dir-target.log" 2>&1
assert_eq "directory at the target still exits 0" "$?" "0"
assert_contains "directory at the target is left alone" "left alone" "$TMPBASE/dir-target.log"
assert_contains "directory at the target is named" "status.md" "$TMPBASE/dir-target.log"
assert_no_file "no wrapper written inside the directory target" "$FORK6/.opencode/commands/status.md/rendered"
bash "$SCRIPT" --root "$FORK6" --check > "$TMPBASE/dir-target-check.log" 2>&1
assert_eq "directory at the target reports no drift under --check" "$?" "0"
assert_contains "directory at the target is a conflict under --check" "name conflict" "$TMPBASE/dir-target-check.log"

echo "symlinks"
# cp writes through a symlink, so a symlinked target would put the wrapper
# outside the output directory.
VICTIM="$TMPBASE/victim.md"
printf 'do not touch\n' > "$VICTIM"
rm -f "$FORK2/.opencode/commands/status.md"
ln -s "$VICTIM" "$FORK2/.opencode/commands/status.md"
bash "$SCRIPT" --root "$FORK2" > "$TMPBASE/symlink1.log" 2>&1
assert_eq "symlinked target still exits 0" "$?" "0"
assert_eq "symlinked target is not written through" "$(cat "$VICTIM")" "do not touch"
rm -f "$FORK2/.opencode/commands/status.md"
ln -s "$TMPBASE" "$FORK2/.opencode/commands-link"
bash "$SCRIPT" --root "$FORK2" --out "$FORK2/.opencode/commands-link" > "$TMPBASE/symlink2.log" 2>&1
assert_eq "symlinked output directory exits 2" "$?" "2"

# A trailing slash must not hide the link: `dirname` drops the leaf and
# `[ -L path/ ]` resolves it, so the path is normalised before the check.
bash "$SCRIPT" --root "$FORK2" --out "$FORK2/.opencode/commands-link/" > "$TMPBASE/symlink3.log" 2>&1
assert_eq "trailing slash does not bypass the symlink check" "$?" "2"

# An explicit --out that crosses a symlink inside the fork must be refused. A
# check of the leaf and its direct parent alone misses a link further up.
mkdir -p "$FORK2/.opencode/real/commands" "$TMPBASE/outside-target"
ln -s "$TMPBASE/outside-target" "$FORK2/.opencode/intermediate"
bash "$SCRIPT" --root "$FORK2" --out "$FORK2/.opencode/intermediate/deeper/commands" > "$TMPBASE/symlink4.log" 2>&1
assert_eq "--out through a symlinked intermediate exits 2" "$?" "2"
assert_no_file "nothing written through an intermediate link" "$TMPBASE/outside-target/deeper/commands/status.md"

# The ancestor can be the link, not the leaf: `.opencode` -> elsewhere moves
# every wrapper out of the fork even though the output directory looks local.
FORK5="$TMPBASE/fork-ancestor"
mkdir -p "$FORK5/.claude/skills/status" "$FORK5/elsewhere"
printf -- '---\nname: status\ndescription: Project snapshot.\n---\n\n# Status\n' \
  > "$FORK5/.claude/skills/status/SKILL.md"
ln -s "$FORK5/elsewhere" "$FORK5/.opencode"
bash "$SCRIPT" --root "$FORK5" > "$TMPBASE/ancestor.log" 2>&1
assert_eq "symlinked ancestor exits 2" "$?" "2"
assert_no_file "nothing written through the ancestor" "$FORK5/elsewhere/status.md"

# A symlink ABOVE the fork does not move a write outside it. A fork under a
# symlinked projects or home folder (and /tmp on macOS) must still generate.
# The root is resolved with `pwd -P`; only the output directory and its parent
# are checked for links.
LINKED_REAL="$TMPBASE/fork-under-link"
make_fork "$LINKED_REAL"
ln -s "$TMPBASE" "$TMPBASE/link-to-tmp"
bash "$SCRIPT" --root "$TMPBASE/link-to-tmp/fork-under-link" > "$TMPBASE/linked-parent.log" 2>&1
assert_eq "fork through a symlinked parent exits 0" "$?" "0"
assert_file "wrapper written under the physical root" "$LINKED_REAL/.opencode/commands/status.md"

echo "description shapes"
# A block-scalar description parses as the indicator itself. The wrapper must
# carry the fallback summary instead of a bare "description: >".
FORK3="$TMPBASE/fork-block"
mkdir -p "$FORK3/.claude/skills/blocky"
printf -- '---\nname: blocky\ndescription: >\n  Two lines\n  of prose.\n---\n\n# Blocky\n' \
  > "$FORK3/.claude/skills/blocky/SKILL.md"
bash "$SCRIPT" --root "$FORK3" > "$TMPBASE/block.log" 2>&1
assert_eq "block-scalar description still generates" "$?" "0"
assert_eq "block-scalar indicator is not emitted as the value" \
  "$(frontmatter_of "$FORK3/.opencode/commands/blocky.md" | sed -n 's/^  //p')" "apexyard /blocky skill"
assert_contains "the fallback is announced" "block-scalar description" "$TMPBASE/block.log"

# A CRLF SKILL.md must still yield its description, with no carriage return
# in the wrapper. A hint with no description still has to reach the palette.
FORK4="$TMPBASE/fork-crlf"
mkdir -p "$FORK4/.claude/skills/crlf" "$FORK4/.claude/skills/hintonly"
printf -- '---\r\nname: crlf\r\ndescription: A windows-authored skill.\r\nargument-hint: "[<id>]"\r\n---\r\n\r\n# CRLF\r\n' \
  > "$FORK4/.claude/skills/crlf/SKILL.md"
printf -- '---\nname: hintonly\nargument-hint: "[<id>]"\n---\n\n# Hint only\n' \
  > "$FORK4/.claude/skills/hintonly/SKILL.md"
bash "$SCRIPT" --root "$FORK4" > "$TMPBASE/crlf.log" 2>&1
assert_eq "CRLF skills still generate" "$?" "0"
assert_contains "CRLF description is parsed" "A windows-authored skill." "$FORK4/.opencode/commands/crlf.md"
assert_eq "no CR reaches the wrapper" \
  "$(tr -cd '\r' < "$FORK4/.opencode/commands/crlf.md" | wc -c | tr -d ' ')" "0"
assert_frontmatter_contains "a hint survives an empty description" "Usage: [<id>]" "$FORK4/.opencode/commands/hintonly.md"

echo "errors"
bash "$SCRIPT" --root "$TMPBASE/does-not-exist" > "$TMPBASE/err1.log" 2>&1
assert_eq "missing skills dir exits 2" "$?" "2"
bash "$SCRIPT" --root "$FORK" --bogus > "$TMPBASE/err2.log" 2>&1
assert_eq "unknown option exits 2" "$?" "2"

echo "checked-in tree"
# The wrappers are a generated, gitignored artifact: adopters create them by
# running the script. This case reads the REAL working tree, so it is opt-in —
# by default it stays out of the suite, where a contributor's stale local
# wrappers would fail a check unrelated to their change.
if [ "${APEXYARD_TEST_LOCAL_COMMANDS:-0}" = "1" ] && [ -d "$ROOT/.opencode/commands" ]; then
  bash "$SCRIPT" --check > "$TMPBASE/check-real.log" 2>&1
  assert_eq "local .opencode/commands matches skills" "$?" "0"
else
  mark_pass "local .opencode/commands not compared (opt in with APEXYARD_TEST_LOCAL_COMMANDS=1)"
fi

echo
if [ "$FAIL" -eq 0 ]; then
  green "PASS ($PASS assertions)"
  exit 0
fi
red "FAIL ($FAIL failed, $PASS passed):$FAILED"
exit 1
