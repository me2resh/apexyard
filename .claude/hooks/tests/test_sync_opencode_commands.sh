#!/usr/bin/env bash
# Tests for bin/sync-opencode-commands.sh — the skill -> opencode slash-command
# generator (me2resh/apexyard#2064).
#
# Hermetic: every case builds its own fixture fork under a temp dir, so the
# checked-in .claude/skills tree and any real .opencode/commands output are
# never touched.

set -u

# Isolate from live Claude Code session pin/cache (me2resh/apexyard#1549).
# shellcheck disable=SC1091
. "$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)/_test-session-isolation.sh"

ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
SCRIPT="$ROOT/bin/sync-opencode-commands.sh"

red()   { printf '\033[31m%s\033[0m\n' "$*"; }
green() { printf '\033[32m%s\033[0m\n' "$*"; }

PASS=0
FAIL=0
FAILED=""

mark_pass() { green "  ok   $1"; PASS=$((PASS + 1)); }
mark_fail() {
  red "  FAIL $1: $2" >&2
  FAIL=$((FAIL + 1))
  FAILED="$FAILED $1"
}

assert_eq() {
  [ "$2" = "$3" ] && mark_pass "$1" || mark_fail "$1" "expected [$3] got [$2]"
}

assert_file() {
  [ -f "$2" ] && mark_pass "$1" || mark_fail "$1" "missing $2"
}

assert_no_file() {
  [ -f "$2" ] && mark_fail "$1" "unexpected $2" || mark_pass "$1"
}

assert_contains() {
  grep -qF "$2" "$3" 2>/dev/null && mark_pass "$1" || mark_fail "$1" "missing [$2] in $3"
}

assert_not_contains() {
  grep -qF "$2" "$3" 2>/dev/null && mark_fail "$1" "unexpected [$2] in $3" || mark_pass "$1"
}

unset CLAUDE_CODE_SESSION_ID
TMPBASE=$(mktemp -d "${TMPDIR:-/tmp}/sync-opencode-commands-test.XXXXXX") || exit 1
trap 'rm -rf "$TMPBASE"' EXIT

# Fixture fork: three usable skills, one dir without SKILL.md, one _lib helper
# file at the skills root, and one skill whose description carries the quoting
# hazards a real SKILL.md has (double quotes, backticks, colon, em dash).
make_fork() {
  local root="$1"
  mkdir -p "$root/.claude/skills/status" \
           "$root/.claude/skills/agdr" \
           "$root/.claude/skills/quote-hazards" \
           "$root/.claude/skills/no-skill-md"
  printf -- '---\nname: status\ndescription: Project snapshot — git state, open PRs.\nallowed-tools: Bash\n---\n\n# Status\n' \
    > "$root/.claude/skills/status/SKILL.md"
  printf -- '---\nname: agdr\ndescription: Browse AgDRs. Recalls "have we decided this before?".\nargument-hint: "[show <id>]"\n---\n\n# AgDR\n' \
    > "$root/.claude/skills/agdr/SKILL.md"
  printf -- '---\ndescription: "Quoted: description with `backticks` and a colon."\n---\n\n# Hazards\n' \
    > "$root/.claude/skills/quote-hazards/SKILL.md"
  printf 'not a skill\n' > "$root/.claude/skills/_lib-helper.sh"
  printf 'placeholder\n' > "$root/.claude/skills/no-skill-md/README.md"
}

FORK="$TMPBASE/fork"
make_fork "$FORK"
OUT="$FORK/.opencode/commands"

echo "generate"
bash "$SCRIPT" --root "$FORK" > "$TMPBASE/run1.log" 2>&1
assert_eq "exit 0 on first run" "$?" "0"
assert_file "status wrapper written" "$OUT/status.md"
assert_file "agdr wrapper written" "$OUT/agdr.md"
assert_file "quote-hazard wrapper written" "$OUT/quote-hazards.md"
assert_no_file "_lib helper is not a skill" "$OUT/_lib-helper.md"
assert_no_file "dir without SKILL.md is skipped" "$OUT/no-skill-md.md"
assert_eq "three wrappers, nothing else" "$(ls "$OUT" | wc -l | tr -d ' ')" "3"
assert_contains "description carried over" "Project snapshot — git state, open PRs." "$OUT/status.md"
assert_contains "quoted description unwrapped" "Quoted: description with" "$OUT/quote-hazards.md"
assert_contains "argument-hint surfaced in the body" "[show <id>]" "$OUT/agdr.md"
assert_contains "body loads the skill by exact id" 'Load the apexyard skill `status`' "$OUT/status.md"
assert_contains "body forwards arguments" '$ARGUMENTS' "$OUT/status.md"
assert_contains "generator marker present" "generated by bin/sync-opencode-commands.sh" "$OUT/status.md"

echo "idempotence"
bash "$SCRIPT" --root "$FORK" > "$TMPBASE/run2.log" 2>&1
assert_eq "exit 0 on second run" "$?" "0"
grep -q '0 written, 3 unchanged' "$TMPBASE/run2.log" \
  && mark_pass "second run rewrites nothing" \
  || mark_fail "second run rewrites nothing" "$(cat "$TMPBASE/run2.log")"

echo "--check"
bash "$SCRIPT" --root "$FORK" --check > "$TMPBASE/check1.log" 2>&1
assert_eq "clean --check exits 0" "$?" "0"

printf '\n<!-- hand edit -->\n' >> "$OUT/status.md"
bash "$SCRIPT" --root "$FORK" --check > "$TMPBASE/check2.log" 2>&1
assert_eq "drifted --check exits 1" "$?" "1"
assert_contains "drift names the file" "$OUT/status.md" "$TMPBASE/check2.log"
assert_contains "drifted file is left as-is by --check" "<!-- hand edit -->" "$OUT/status.md"

bash "$SCRIPT" --root "$FORK" > /dev/null 2>&1
assert_not_contains "regeneration reverts the drift" "<!-- hand edit -->" "$OUT/status.md"

echo "pruning"
cp "$OUT/status.md" "$OUT/gone-skill.md"
bash "$SCRIPT" --root "$FORK" --check > "$TMPBASE/check3.log" 2>&1
assert_eq "stale generated wrapper is drift" "$?" "1"
assert_file "stale wrapper survives --check" "$OUT/gone-skill.md"
bash "$SCRIPT" --root "$FORK" > "$TMPBASE/run3.log" 2>&1
assert_no_file "stale generated wrapper pruned" "$OUT/gone-skill.md"

printf 'Review $ARGUMENTS.\n' > "$OUT/handwritten.md"
bash "$SCRIPT" --root "$FORK" > /dev/null 2>&1
assert_file "hand-written wrapper is never pruned" "$OUT/handwritten.md"
rm -f "$OUT/handwritten.md"

echo "errors"
bash "$SCRIPT" --root "$TMPBASE/does-not-exist" > "$TMPBASE/err1.log" 2>&1
assert_eq "missing skills dir exits 2" "$?" "2"
bash "$SCRIPT" --root "$FORK" --bogus > "$TMPBASE/err2.log" 2>&1
assert_eq "unknown option exits 2" "$?" "2"

echo "checked-in tree"
# The wrappers are a generated, gitignored artifact: adopters create them by
# running the script. When a working tree does have them, they must match the
# skills tree — the same guard an adopter can wire into CI.
if [ -d "$ROOT/.opencode/commands" ]; then
  bash "$SCRIPT" --check > "$TMPBASE/check-real.log" 2>&1
  assert_eq "local .opencode/commands matches skills" "$?" "0"
else
  mark_pass "no local .opencode/commands to compare (generated artifact)"
fi

echo
if [ "$FAIL" -eq 0 ]; then
  green "PASS ($PASS assertions)"
  exit 0
fi
red "FAIL ($FAIL failed, $PASS passed):$FAILED"
exit 1
