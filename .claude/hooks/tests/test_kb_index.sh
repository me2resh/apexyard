#!/bin/bash
# Tests for bin/kb-index.
set -u

# shellcheck disable=SC1091
. "$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)/_test-session-isolation.sh"

TEST_DIR=$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)
REPO_ROOT=$(cd "$TEST_DIR/../../.." && pwd)
INDEX="$REPO_ROOT/bin/kb-index"
MIGRATE="$REPO_ROOT/bin/kb-migrate"

PASS=0
FAIL=0
pass() { PASS=$((PASS + 1)); echo "PASS: $1"; }
fail() { FAIL=$((FAIL + 1)); echo "FAIL: $1 — $2"; }

FX=$(mktemp -d)
trap 'rm -rf "$FX"' EXIT

git -C "$FX" init -q
mkdir -p "$FX/handbooks/architecture" "$FX/handbooks/language/typescript"

cat > "$FX/handbooks/architecture/alpha.md" <<'MD'
# Handbook: Alpha

Body.
MD
cat > "$FX/handbooks/architecture/zeta.md" <<'MD'
# Handbook: Zeta

Body.
MD
cat > "$FX/handbooks/README.md" <<'MD'
# README should not be an entry
MD
cat > "$FX/handbooks/language/typescript/strict.md" <<'MD'
# Handbook: Strict Mode

Body.
MD

git -C "$FX" add handbooks
GIT_AUTHOR_DATE='2024-01-15T12:00:00' GIT_COMMITTER_DATE='2024-01-15T12:00:00' \
  git -C "$FX" -c user.name='Bob' -c user.email='b@example.com' commit -q -m 'h'

"$MIGRATE" --root "$FX" >/dev/null

"$INDEX" --root "$FX" >/dev/null

idx="$FX/handbooks/architecture/index.md"
[ -f "$idx" ] && pass "architecture index exists" || fail "architecture index exists" ""
head -n 1 "$idx" | grep -q 'generated by bin/kb-index' && pass "generated marker" || fail "generated marker" "$(head -n 1 "$idx")"

grep -q 'Alpha' "$idx" && pass "lists Alpha" || fail "lists Alpha" ""
grep -q 'Zeta' "$idx" && pass "lists Zeta" || fail "lists Zeta" ""
grep -q 'README' "$idx" && fail "README not listed" "found README" || pass "README not listed"
grep -q 'index.md' "$idx" && fail "index.md not listed as entry" "found" || pass "index.md not listed as entry"

# Deterministic: alpha before zeta in table (sorted by filename)
alpha_line=$(grep -n 'alpha.md' "$idx" | head -1 | cut -d: -f1)
zeta_line=$(grep -n 'zeta.md' "$idx" | head -1 | cut -d: -f1)
[ "$alpha_line" -lt "$zeta_line" ] && pass "sorted by filename" || fail "sorted by filename" "alpha=$alpha_line zeta=$zeta_line"

# Sub-folder link from language/
lang_idx="$FX/handbooks/language/index.md"
grep -q 'typescript/index.md' "$lang_idx" && pass "sub-folder link" || fail "sub-folder link" "$(cat "$lang_idx")"

# --check clean
if "$INDEX" --root "$FX" --check; then
  pass "check clean exit 0"
else
  fail "check clean exit 0" "exit $?"
fi

# --check drift
echo 'tamper' >> "$idx"
if "$INDEX" --root "$FX" --check; then
  fail "check drift exit 1" "exit 0"
else
  pass "check drift exit 1"
fi

# Deterministic second write
"$INDEX" --root "$FX" >/dev/null
h1=$(if command -v shasum >/dev/null; then shasum -a 256 "$FX/handbooks/architecture/index.md" | awk '{print $1}'; else sha256sum "$FX/handbooks/architecture/index.md" | awk '{print $1}'; fi)
"$INDEX" --root "$FX" >/dev/null
h2=$(if command -v shasum >/dev/null; then shasum -a 256 "$FX/handbooks/architecture/index.md" | awk '{print $1}'; else sha256sum "$FX/handbooks/architecture/index.md" | awk '{print $1}'; fi)
[ "$h1" = "$h2" ] && pass "deterministic rewrite" || fail "deterministic rewrite" ""

echo
echo "Total: $((PASS + FAIL))  Passed: $PASS  Failed: $FAIL"
[ "$FAIL" -eq 0 ]
