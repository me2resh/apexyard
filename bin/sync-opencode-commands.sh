#!/usr/bin/env bash
# Generate opencode slash-command wrappers from apexyard skills.
#
# In Claude Code, every .claude/skills/<id>/SKILL.md is also the /<id> slash
# command. opencode discovers the same tree as a *skill* source, but its slash
# commands come only from .opencode/commands/*.md. This generator closes that
# gap: one wrapper per skill, so the operator keeps an explicit /<id> entry
# point on the opencode harness instead of relying on model-side skill
# selection.
#
#   .claude/skills/<id>/SKILL.md  ->  .opencode/commands/<id>.md
#
# The wrapper body tells the agent to load the skill by its exact ID with the
# skill tool and to forward the command's arguments. Skill content is never
# copied: the SKILL.md stays the single source of truth, so a skill edit needs
# no wrapper regen beyond `description` / `argument-hint` drift.
#
# Usage:
#   bin/sync-opencode-commands.sh            # write/refresh wrappers, prune stale
#   bin/sync-opencode-commands.sh --check    # write nothing; exit 1 on drift
#   bin/sync-opencode-commands.sh --root <fork> [--out <dir>]
#
# Exit codes: 0 clean, 1 drift (--check only), 2 usage error.
#
# Generated wrappers are disposable. They are pruned only when they carry the
# generator marker, so a hand-written .opencode/commands/*.md is never removed.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SKILLS_DIR=""
OUT_DIR="$ROOT/.opencode/commands"
OUT_EXPLICIT=0
CHECK=0

MARKER='<!-- generated by bin/sync-opencode-commands.sh — regenerate, do not hand-edit -->'

usage() {
  cat <<'USAGE'
Usage: bin/sync-opencode-commands.sh [--check] [--root <path>] [--out <dir>]

Generate opencode slash-command wrappers, one per apexyard skill:
  .claude/skills/<id>/SKILL.md  ->  .opencode/commands/<id>.md

Options:
  --check        Write nothing; exit 1 and list the wrappers that are stale.
  --root PATH    Fork root to read skills from (default: this script's parent).
  --out DIR      Output directory (default: <root>/.opencode/commands).
  -h, --help     Show this help.
USAGE
}

while [ $# -gt 0 ]; do
  case "$1" in
    --check) CHECK=1 ;;
    --root)
      [ $# -ge 2 ] || { echo "sync-opencode-commands: --root needs a path" >&2; exit 2; }
      ROOT="$2"
      [ "$OUT_EXPLICIT" -eq 1 ] || OUT_DIR="$ROOT/.opencode/commands"
      shift
      ;;
    --out)
      [ $# -ge 2 ] || { echo "sync-opencode-commands: --out needs a path" >&2; exit 2; }
      OUT_DIR="$2"
      OUT_EXPLICIT=1
      shift
      ;;
    -h|--help) usage; exit 0 ;;
    *) echo "sync-opencode-commands: unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

[ -d "$ROOT" ] || { echo "sync-opencode-commands: no such directory: $ROOT" >&2; exit 2; }
ROOT="$(cd "$ROOT" && pwd)"
SKILLS_DIR="$ROOT/.claude/skills"

[ -d "$SKILLS_DIR" ] || { echo "sync-opencode-commands: no skills directory at $SKILLS_DIR" >&2; exit 2; }

# frontmatter_value <file> <key>
# Prints the first "key: value" line of the leading YAML block, unwrapped from
# surrounding quotes. Prints nothing when the key is absent.
frontmatter_value() {
  awk -v key="$2" '
    BEGIN { sq = sprintf("%c", 39) }
    NR == 1 && $0 != "---" { exit }
    NR == 1 { inside = 1; next }
    inside && $0 == "---" { exit }
    inside && index($0, key ":") == 1 {
      line = $0
      sub("^" key ":[ ]*", "", line)
      if (length(line) >= 2) {
        first = substr(line, 1, 1)
        last = substr(line, length(line), 1)
        if ((first == "\"" && last == "\"") || (first == sq && last == sq)) {
          line = substr(line, 2, length(line) - 2)
        }
      }
      print line
      exit
    }
  ' "$1"
}

# Body of one wrapper. Kept deliberately short: the skill owns the behaviour.
wrapper_content() {
  local id="$1" hint="$2"
  cat <<EOF
$MARKER

Load the apexyard skill \`$id\` with the skill tool and follow it exactly. It is
the operator-invoked /$id command; do not substitute a summary of your own for
what the skill prescribes.
EOF
  if [ -n "$hint" ]; then
    printf '\nUsage for this command: `%s`\n' "${hint//\`/}"
  fi
  printf '\n$ARGUMENTS\n'
}

TMPBASE="$(mktemp -d "${TMPDIR:-/tmp}/sync-opencode-commands.XXXXXX")"
trap 'rm -rf "$TMPBASE"' EXIT

: > "$TMPBASE/expected"
: > "$TMPBASE/drift"
generated=0
unchanged=0
pruned=0

for skill_dir in "$SKILLS_DIR"/*/; do
  [ -d "$skill_dir" ] || continue
  id="$(basename "$skill_dir")"
  case "$id" in _*|.*) continue ;; esac
  skill_file="$skill_dir/SKILL.md"
  [ -f "$skill_file" ] || continue
  case "$id" in
    *[!a-zA-Z0-9._-]*)
      printf 'sync-opencode-commands: skipping %s (not a safe command name)\n' "$id" >&2
      continue
      ;;
  esac

  description="$(frontmatter_value "$skill_file" description)"
  hint="$(frontmatter_value "$skill_file" argument-hint)"
  target="$OUT_DIR/$id.md"
  printf '%s\n' "$target" >> "$TMPBASE/expected"

  {
    printf -- '---\n'
    if [ -n "$description" ]; then
      # Block scalar: safe for colons, quotes, backticks and em dashes.
      printf 'description: >-\n  %s\n' "${description//$'\n'/ }"
    else
      printf 'description: >-\n  apexyard /%s skill\n' "$id"
    fi
    printf -- '---\n'
    wrapper_content "$id" "$hint"
  } > "$TMPBASE/rendered"

  if [ -f "$target" ] && cmp -s "$TMPBASE/rendered" "$target"; then
    unchanged=$((unchanged + 1))
    continue
  fi

  if [ "$CHECK" -eq 1 ]; then
    printf '%s\n' "$target" >> "$TMPBASE/drift"
    continue
  fi

  mkdir -p "$OUT_DIR"
  cp "$TMPBASE/rendered" "$target"
  generated=$((generated + 1))
done

# Prune stale wrappers this generator wrote earlier. Anything without the
# marker is left alone: it belongs to the operator, not to us.
if [ -d "$OUT_DIR" ]; then
  for existing in "$OUT_DIR"/*.md; do
    [ -f "$existing" ] || continue
    grep -qF "$MARKER" "$existing" || continue
    grep -qxF "$existing" "$TMPBASE/expected" && continue
    if [ "$CHECK" -eq 1 ]; then
      printf '%s\n' "$existing" >> "$TMPBASE/drift"
    else
      rm -f "$existing"
      pruned=$((pruned + 1))
    fi
  done
fi

if [ "$CHECK" -eq 1 ]; then
  if [ -s "$TMPBASE/drift" ]; then
    echo "opencode commands out of date:" >&2
    sed 's/^/  /' "$TMPBASE/drift" >&2
    echo "Run bin/sync-opencode-commands.sh to refresh them." >&2
    exit 1
  fi
  echo "opencode commands up to date ($unchanged wrappers in $OUT_DIR)."
  exit 0
fi

echo "opencode commands: $generated written, $unchanged unchanged, $pruned pruned ($OUT_DIR)."
