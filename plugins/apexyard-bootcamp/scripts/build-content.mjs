// Build-time only. The runtime imports strings and never reads files.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
const root = new URL('../', import.meta.url)
export function generatedContent() {
  const files = readdirSync(new URL('content/', root)).filter(f => /^\d{2}-[a-z0-9-]+\.md$/.test(f)).sort()
  return '// Generated by scripts/build-content.mjs. Do not edit.\nexport const content = '
    + JSON.stringify(files.map(file => ({ file, text: readFileSync(new URL(`content/${file}`, root), 'utf8') })), null, 2)
    + ' as const\n'
}
const target = new URL('hooks/content.generated.ts', root)
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generatedContent()) throw new Error('Bundled content is stale. Run node scripts/build-content.mjs.')
} else writeFileSync(target, generatedContent())
